/**
 * Storage abstraction for user-uploaded files (product images today).
 *
 * Business code depends only on this interface. The current implementation
 * writes to a local directory mounted as a persistent volume
 * (`LocalDiskStorage`); an OCI Object Storage implementation can replace it
 * later without touching callers.
 */
export interface StoredObject {
  data: Buffer;
  contentType: string;
}

export interface StorageProvider {
  /** Store `data` under `key`, replacing any previous object. */
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  /** Read an object; `null` when it does not exist. */
  get(key: string): Promise<StoredObject | null>;
  /** Delete an object; deleting a missing key is not an error. */
  delete(key: string): Promise<void>;
  /** Public URL (path) under which the object is served. */
  url(key: string): string;
  /** Inverse of `url`: the key behind a URL produced by this provider, or `null`. */
  keyFromUrl(url: string): string | null;
}

/**
 * Keys are generated by the server only: `<segment>/<segment>/.../<name>.<ext>`
 * with a conservative charset. This blocks path traversal (`..`, absolute
 * paths, backslashes, encoded separators) before any provider sees the key.
 */
const SEGMENT = /^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$/;
const FILE_NAME = /^[A-Za-z0-9][A-Za-z0-9_-]{0,63}\.(webp)$/;

export function isValidKey(key: string): boolean {
  if (typeof key !== 'string' || key.length === 0 || key.length > 512) return false;
  const parts = key.split('/');
  if (parts.length < 2) return false;
  const fileName = parts[parts.length - 1];
  return parts.slice(0, -1).every((p) => SEGMENT.test(p)) && FILE_NAME.test(fileName);
}

export function assertValidKey(key: string): void {
  if (!isValidKey(key)) throw new Error('Invalid storage key');
}

export const PRODUCT_IMAGE_FOLDER = 'products';

/** `<organizationId>/products/<id>.webp` — every image is namespaced by organization. */
export function productImageKey(organizationId: string, id: string): string {
  const key = `${organizationId}/${PRODUCT_IMAGE_FOLDER}/${id}.webp`;
  assertValidKey(key);
  return key;
}

/** True when `key` is a product image that belongs to `organizationId`. */
export function isOrgProductImageKey(key: string, organizationId: string): boolean {
  return isValidKey(key) && key.startsWith(`${organizationId}/${PRODUCT_IMAGE_FOLDER}/`) && key.split('/').length === 3;
}
